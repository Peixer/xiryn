// Build the root oneshot into one JavaScript file.
//
// /usr/local/sbin/xiryn-helper runs that file with system node, outside the
// checkout. A colour tree is owned by the service user, so the oneshot must
// not load TypeScript from it and must not ask tsx to resolve @/.
import { build } from "esbuild"
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..")
const outfile = path.resolve(
  process.argv[2] ?? path.join(root, "deploy/xiryn-helper.mjs")
)

const result = await build({
  absWorkingDir: root,
  entryPoints: ["deploy/xiryn-helper.ts"],
  bundle: true,
  platform: "node",
  format: "esm",
  target: "node22",
  outfile,
  legalComments: "none",
  logLevel: "warning",
  metafile: true,
  banner: {
    js: "// Generated by scripts/bundle-xiryn-helper.mjs. Do not edit.\n",
  },
})

const inputs = Object.keys(result.metafile?.inputs ?? {})
for (const input of inputs) {
  if (input.includes("node_modules") || input.startsWith("..")) {
    throw new Error(`Helper bundle must stay inside this repo, not ${input}`)
  }
}

const source = fs.readFileSync(outfile, "utf8")
if (/from\s+["']@\//.test(source)) {
  throw new Error("Helper bundle still imports @/.")
}
